//! SeaORM model matching the original toasty model.

use sea_orm::entity::prelude::*;

/// A token used to authorize requests
///
/// A token MUST be related to a [`User`](super::users::Model), and MAY be related to a [`GameProfile`](super::game_profiles::Model).
#[sea_orm::model]
#[derive(Clone, Debug, PartialEq, Eq, DeriveEntityModel)]
#[sea_orm(table_name = "tokens")]
pub struct Model {
    /// The access token of this Token
    ///
    /// An access token is a UUID that the Server allocated to the user.
    #[sea_orm(primary_key, auto_increment = false)]
    pub access_token: Uuid,
    /// Internal field
    #[sea_orm(indexed)]
    pub user_id: Uuid,
    /// The client token of this Token
    ///
    /// A client token is a string generated by the client to distinct different clients of a user
    #[sea_orm(column_type = "Text")]
    pub client_token: String,
    /// The creation time of this token
    pub created_at: DateTimeUtc,
    /// Internal field
    #[sea_orm(indexed)]
    pub profile_id: Option<Uuid>,
    /// The User this token belongs to
    #[sea_orm(belongs_to, from = "user_id", to = "id")]
    pub user: BelongsTo<super::users::Entity>,
    /// The Minecraft player profile this token is associated with
    #[sea_orm(belongs_to, from = "profile_id", to = "id")]
    pub profile: BelongsTo<Option<super::game_profiles::Entity>>,
}

#[async_trait::async_trait]
impl ActiveModelBehavior for ActiveModel {
    async fn before_save<C>(mut self, _db: &C, insert: bool) -> Result<Self, DbErr>
    where
        C: ConnectionTrait,
    {
        if insert && self.access_token.is_not_set() {
            self.access_token = sea_orm::Set(Uuid::now_v7());
        }
        if insert && self.created_at.is_not_set() {
            self.created_at = sea_orm::Set(ChronoUtc::now());
        }
        Ok(self)
    }
}
